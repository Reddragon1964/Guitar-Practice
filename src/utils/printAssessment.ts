/**
 * Clean, robust printer and export utility for AI Practice Coach Assessments.
 * Supports direct document printing, standalone HTML report download,
 * structured text export, and clipboard copying.
 */

export interface AssessmentData {
  date: string;
  time: string;
  analysis: string;
  sessionCount?: number;
}

